// package.json is the only place the Orbis version is written by hand. This script copies it into
// src/version.ts (used by the CLI, MCP, CDP and WebDriver servers) and the Python package.
//
//   node scripts/sync-version.mjs          update the files
//   node scripts/sync-version.mjs --check  exit 1 if any file differs (CI, tests)
//
// It runs on every build and on `npm version <patch|minor|major>`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error(`package.json version "${version}" is not a valid semver`);
  process.exit(1);
}
// PEP 440 spelling of a pre-release: 0.2.0-rc.1 -> 0.2.0rc1
const pyVersion = version.replace(/-(alpha|beta|rc)\.?(\d+)$/, (_m, tag, n) => `${{ alpha: 'a', beta: 'b', rc: 'rc' }[tag]}${n}`);

const targets = [
  {
    file: 'src/version.ts',
    render: () => `// Generated by scripts/sync-version.mjs from package.json. Do not edit by hand.\nexport const ORBIS_VERSION = '${version}';\n`,
  },
  { file: 'python/pyproject.toml', pattern: /^version = "[^"]*"/m, value: `version = "${pyVersion}"` },
  { file: 'python/memora/__init__.py', pattern: /^__version__ = "[^"]*"/m, value: `__version__ = "${pyVersion}"` },
  { file: 'python/orbis/__init__.py', pattern: /^__version__ = "[^"]*"/m, value: `__version__ = "${pyVersion}"` },
];

const check = process.argv.includes('--check');
const stale = [];
for (const t of targets) {
  const file = path.join(root, t.file);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  let next;
  if (t.render) {
    next = t.render();
  } else {
    if (!t.pattern.test(current)) {
      console.error(`${t.file}: no version line found`);
      process.exit(1);
    }
    next = current.replace(t.pattern, t.value);
  }
  if (next === current) continue;
  stale.push(t.file);
  if (!check) fs.writeFileSync(file, next);
}

if (check && stale.length) {
  console.error(`Version ${version} from package.json is not in: ${stale.join(', ')}. Run: node scripts/sync-version.mjs`);
  process.exit(1);
}
console.log(stale.length ? `Version ${version} written to ${stale.join(', ')}` : `Version ${version}: all files in sync`);
